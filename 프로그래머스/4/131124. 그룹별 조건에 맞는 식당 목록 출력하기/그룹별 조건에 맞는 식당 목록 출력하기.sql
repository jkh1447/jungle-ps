


SELECT P.MEMBER_NAME, R.REVIEW_TEXT, R.REVIEW_DATE
FROM 
MEMBER_PROFILE P
JOIN REST_REVIEW R
ON P.MEMBER_ID = R.MEMBER_ID
WHERE R.MEMBER_ID =
(
    SELECT MEMBER_ID 
    FROM (
        SELECT MEMBER_ID
        FROM REST_REVIEW
        GROUP BY MEMBER_ID
        ORDER BY COUNT(*) DESC
        LIMIT 1
        ) SUB
) 
ORDER BY R.REVIEW_DATE, R.REVIEW_TEXT









