



SELECT CAR_ID,
    MAX(CASE
        WHEN START_DATE <= '2022-10-16' AND '2022-10-16' <= END_DATE THEN '대여중'
        WHEN '2022-10-16' > END_DATE THEN '대여 가능'
        WHEN '2022-10-16' < START_DATE THEN '대여 가능'
    END) AS AVAILABILITY
FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY
GROUP BY CAR_ID
ORDER BY CAR_ID DESC










