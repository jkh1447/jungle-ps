

SELECT S.ID, 
    CASE
        WHEN S.QUAL = 1 THEN 'CRITICAL'
        WHEN S.QUAL = 2 THEN 'HIGH'
        WHEN S.QUAL = 3 THEN 'MEDIUM'
        WHEN S.QUAL = 4 THEN 'LOW'
    END AS COLONY_NAME
FROM (
    SELECT *, NTILE(4) OVER(ORDER BY SIZE_OF_COLONY DESC) AS QUAL
    FROM ECOLI_DATA
) S
ORDER BY S.ID 
























