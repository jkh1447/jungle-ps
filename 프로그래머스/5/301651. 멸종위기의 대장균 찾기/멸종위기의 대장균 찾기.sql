

WITH RECURSIVE GENS AS (
    SELECT ID, 1 AS GEN
    FROM ECOLI_DATA
    WHERE PARENT_ID IS NULL
    
    UNION ALL 
    
    SELECT D.ID, G.GEN + 1 AS GEN  
    FROM GENS G JOIN ECOLI_DATA D ON G.ID = D.PARENT_ID

)

SELECT COUNT(*) AS COUNT, G.GEN AS GENERATION
FROM GENS G JOIN ECOLI_DATA E ON G.ID = E.ID LEFT JOIN ECOLI_DATA E2 ON E.ID = E2.PARENT_ID
WHERE E2.ID IS NULL
GROUP BY G.GEN
ORDER BY G.GEN












